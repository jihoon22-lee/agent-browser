import test from "node:test";
import assert from "node:assert/strict";
import { runtimeConfig } from "./runtime.ts";

test("Linux defaults remain the test bridge and Playwright Chromium", () => {
  const config = runtimeConfig({}, "linux", "/repo");
  assert.equal(config.bridgeExe, "/repo/target/debug/browser-bridge");
  assert.equal(config.extensionDir, "/repo/extension/dist");
  assert.equal(config.browserExecutable, undefined);
  assert.equal(config.headless, true);
});

test("Windows defaults use the built exe and installed branded Chrome", () => {
  const config = runtimeConfig({ ProgramFiles: "C:\\Program Files" }, "win32", "C:\\testing");
  assert.equal(config.bridgeExe, "C:\\testing\\target\\x86_64-pc-windows-msvc\\release\\browser-bridge.exe");
  assert.equal(config.browserExecutable, "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe");
  assert.equal(config.nativeWindows, true);
});

test("explicit native paths including spaces and Korean stay intact", () => {
  const config = runtimeConfig({
    AB_BRIDGE_EXE: "C:\\Agent Browser 테스트\\browser-bridge.exe",
    AB_EXTENSION_DIR: "C:\\AgentBrowser-dev\\extension",
    AB_BROWSER_EXECUTABLE: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
    AB_HEADED: "1", AB_WORK_ROOT: "C:\\AgentBrowser-dev\\testing\\work",
  }, "win32", "C:\\testing");
  assert.equal(config.bridgeExe, "C:\\Agent Browser 테스트\\browser-bridge.exe");
  assert.equal(config.extensionDir, "C:\\AgentBrowser-dev\\extension");
  assert.equal(config.headless, false);
  assert.equal(config.workRoot, "C:\\AgentBrowser-dev\\testing\\work");
});

test("Windows evidence cannot be generated by a Linux process", () => {
  assert.throws(() => runtimeConfig({ AB_E2E_PLATFORM: "windows" }, "linux", "/repo"), /native Windows Node/);
});

test("external fixture stays loopback and uses both configured origins", () => {
  const config = runtimeConfig({ AB_FIXTURE_BASE: "http://127.0.0.1:8790/", AB_FIXTURE_ALT: "8791" }, "win32", "C:\\testing");
  assert.deepEqual(config.externalFixture, { base: "http://127.0.0.1:8790", alt: 8791 });
  assert.throws(() => runtimeConfig({ AB_FIXTURE_BASE: "https://example.com", AB_FIXTURE_ALT: "8791" }), /loopback/);
  assert.throws(() => runtimeConfig({ AB_FIXTURE_BASE: "http://127.0.0.1:8790" }), /together/);
});
